  function getStored() {
    try { return localStorage.getItem(LANG_KEY); } catch (e) { return null; }
  }
  function setStored(lang) {
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}
  }

  function applyLanguage(lang) {
    window.currentLang = lang;
    document.documentElement.lang = lang === 'en' ? 'en' : (lang === 'ja' ? 'ja' : 'zh-Hant');

    var dict = T[lang];
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (!dict) {
        if (el.hasAttribute('data-i18n-zh-orig')) {
          el.innerHTML = el.getAttribute('data-i18n-zh-orig');
        }
        return;
      }
      if (!el.hasAttribute('data-i18n-zh-orig')) {
        el.setAttribute('data-i18n-zh-orig', el.innerHTML);
      }
      var text = dict[key];
      if (text === undefined) {
        el.innerHTML = el.getAttribute('data-i18n-zh-orig');
      } else {
        el.innerHTML = text;
      }
    });

    document.querySelectorAll('.lang-switch button').forEach(function (btn) {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    setStored(lang);
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang: lang } }));
  }

  document.addEventListener('DOMContentLoaded', function () {
    document.querySelectorAll('.lang-switch button').forEach(function (btn) {
      btn.addEventListener('click', function () { applyLanguage(btn.dataset.lang); });
    });
    applyLanguage(getStored() || 'zh');
  });
